# Codex 命令行（ChatGPT.app 自带 image_gen，Plus 额度）；画风参考第一章草原底图。放 美术/讨伐/底图/<键>.png，已有的跳过。
# 用法：bash 三国志/工具/画图/draw_hunt_bg.sh
C="/Applications/ChatGPT.app/Contents/Resources/codex-cli/CodexCLI.app/Contents/MacOS/codex"
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../.." && pwd)"; OUT="$ROOT/美术/讨伐/底图"; mkdir -p "$OUT/log"
REF="$ROOT/美术/底图原色/bg_grass.jpg"
COMMON="竖版 2:3 的游戏战场底图，只画一张完整的图（不要拼图、不要用代码裁切）。镜头在我方武将身后稍高处往前看：画面上方约四分之一是远景和天空（远景画清楚、有体积）；画面正中间是一大片开阔平坦的空地（一只巨大的怪物会站在这里，所以正中不要摆石头、树、建筑）；画面下方三分之一也是平坦的地面（我方三个武将站在这里），一直铺到画面最下沿。整张图不要城墙、城垛、栏杆、栅栏、砖石走道。左右两边边缘可以有景物把场地围起来。地面有几大块颜色斑块和柔和的明暗起伏，近大远小有纵深，不要满地碎点。
画风：和附图是同一套游戏的战场底图：明亮、饱和的厚涂游戏插画，大色块打底，远近有层次。只学附图的上色、笔触和镜头高度，不照抄它的地点和构图。
不要：水墨、淡彩；任何文字、汉字、符号；人物、马匹、动物、怪物（一个都不要）；现代物品；满屏密集重复的小点、颗粒、碎屑、噪点。"
draw() { local id="$1" p="$2"
  [ -f "$OUT/$id.png" ] && { echo "have $id"; return; }
  printf "%s" "用内置 image_gen 工具画一张图（只画这一张，不要写代码）。画完把图片文件复制到 $OUT/$id.png 然后结束。附图是画风参考。
画面：$p
$COMMON" | (cd "$OUT" && "$C" exec --skip-git-repo-check -s workspace-write -i "$REF" - > "log/$id.txt" 2>&1)
  if [ -f "$OUT/$id.png" ]; then echo "ok $id"; elif grep -q "429\|usage_limit" "$OUT/log/$id.txt"; then echo "额度用完，停在 $id"; exit 1; else echo "没画出 $id（看 log/$id.txt）"; fi
}
draw bg_hunt_altar "黄巾祭坛：黄昏的旷野，远处正中是一座夯土筑的三层祭坛，坛顶一口大铜鼎冒着青烟；祭坛两侧各插一排高高的黄色长幡在风里飘；场地左右边缘是几只烧着火的铁火盆和几根插在地上的木桩；地面是踩实的黄褐色土地，中间一大片被烧黑又发亮的圆形焦土；天空是暗金色和紫灰色的晚霞，云压得很低。"
draw bg_hunt_forest "深山林间空地：清晨，四周是高大的古松和成片的翠竹，把一块平坦的林间空地围在中间；远处是一层层青灰色的山峰和从山间落下的一线瀑布，薄雾缭绕；空地地面是深绿的苔草和褐色落叶的大色块，左右边缘有几块长着青苔的巨石和倒伏的枯树；阳光从树冠缝隙里斜着照下几道光柱。"
draw bg_hunt_river "大河滩：阴天，远处一条宽阔的大河横贯画面，河水青黑、翻着白浪，对岸是模糊的青灰色山影；河这边是一大片平坦湿润的浅色沙石河滩，几处浅水洼映着天光；左右边缘是成片的芦苇和几块被水冲圆的大石头、半埋在沙里的破木船；天空是厚重的铅灰色雨云，云缝里透出一道青白的光。"
