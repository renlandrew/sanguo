    if k.startswith('story') and k not in ('story_guan', 'story_liu', 'story_zhang', 'story_zhangjiao'): parts.append('画面里最多只有一个张飞：其他诸侯、将领、士兵、路人都不许穿红黑铠甲、不许戴红头巾、不许留张飞那样的络腮胡，长相和衣服颜色都要跟张飞明显不同。')   # 10-27 用户圈第 12 张：「这2个一个样」
