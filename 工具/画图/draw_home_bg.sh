REF="$ROOT/原型/img/bg_peach.jpg"
COMMON="这是手机游戏（竖屏）主界面的背景图，画面上会另外叠三个武将立绘和按钮，所以：
- 绝对不要画任何人物、动物、文字、按钮、边框、水印。
- 竖图，高大于宽。
- 构图分区（从上往下）：最上面约 15% 是比较干净的天空（会压顶栏）；中间是远景和中景；画面高度约 68%–82% 的位置是一块平整、开阔、空着的地面（三个武将会站在这里，脚踩在约 80% 高处），地面往两边延伸；最下面 20% 会被按钮盖住，随便画地面延伸即可。
- 重要的景物放在左右两侧和远处，画面正中间那一竖条（人物要站的地方）保持开阔、不要有树干、柱子挡住。左右各 8% 可能被裁掉，不要放关键内容。
- 画风：明亮、饱和、通透的国风手游场景原画，干净的厚涂上色，光感强、空气透视清楚，像精致的商业二次元三国手游的主界面背景。整体亮度要高，暗部也要通透，不要大片死黑，不要阴沉。附图是本游戏现有的一张关卡底图，色彩和笔触可以参考它的明亮程度，但构图按上面的要求重新画。"
draw() { # id 提示词
  local id="$1" p="$2"
  [ -f "$OUT/$id.png" ] && { echo "have $id"; return; }
  printf "%s" "用内置 image_gen 工具画一张图（只画这一张，不要写代码处理图片）。画完把图片文件复制到 $OUT/$id.png 然后结束。
$COMMON
场景：$p" | (cd "$OUT" && "$C" exec --skip-git-repo-check -s workspace-write -i "$REF" - > "log/$id.txt" 2>&1)
  if [ -f "$OUT/$id.png" ]; then echo "ok $id"; elif grep -q "429\|usage limit\|usage_limit" "$OUT/log/$id.txt"; then echo "额度用完，停在 $id"; exit 1; else echo "没画出 $id（看 log/$id.txt）"; fi
}
draw home_peach "春日桃园。晴朗的上午，天空湛蓝有几朵白云；左右两侧是盛开的粉色桃树，花瓣飘落；远处是青绿的山峦和一座小村庄、一座木亭；中景有一条小溪和石桥；人物要站的地方是一片铺着落花的平整草地和青石平台。暖阳从右上方照下来，整体粉、绿、金、蓝，清新明亮。"
