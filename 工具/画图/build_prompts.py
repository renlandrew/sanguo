def body(k, p):
    p = p.split('画风要求')[0]
    p = re.sub(r'（只用图像生成[^）]*）', '', p)
    p = re.sub(r'人物：刘备[^。]*。', '', p)                                       # 统一换成下面的造型段
    p = p.replace('主体放在画面中上部，下面四分之一是地面。', '')
    p = p.replace('红袍外罩黑甲，', '').replace('邹靖：幽州校尉，八字胡，', '邹靖：幽州校尉，').replace('一员穿红袍黑甲、八字胡的校尉邹靖', '校尉邹靖').replace('三兄弟', '刘备、关羽、张飞三兄弟')   # 邹靖不再穿红黑
    return p.strip()

