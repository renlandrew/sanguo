HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../.." && pwd)"; OUT="$ROOT/美术/界面/新图标"; mkdir -p "$OUT/log"
STYLE="风格：国风 Q 版手机游戏的 UI 图标。造型厚实饱满、有体积感，主体是金属金色（亮金高光、橙金中间调、深褐暗部），每个图标外面一圈均匀的深褐色粗描边，顶部有一块明显的高光反光，少量红宝石、翠玉、朱红做点缀色。要像精致的商业手游图标：干净、圆润、对比强、小尺寸也认得出。不要写实油画、不要扁平矢量、不要线稿、不要水墨。"
draw() { # id 提示词
  local id="$1" p="$2"
  [ -f "$OUT/$id.png" ] && { echo "have $id"; return; }
  printf "%s" "用内置 image_gen 工具画一张图（只画这一张，不要写代码处理图片）。画完把图片文件复制到 $OUT/$id.png 然后结束。
$p
$STYLE
背景必须完全透明（PNG 透明通道）。不要文字、不要字母数字、不要格子线、不要底板或按钮框、不要地面投影。正方形画布。" | (cd "$OUT" && "$C" exec --skip-git-repo-check -s workspace-write - > "log/$id.txt" 2>&1)
  if [ -f "$OUT/$id.png" ]; then echo "ok $id"; elif grep -q "429\|usage limit\|usage_limit" "$OUT/log/$id.txt"; then echo "额度用完，停在 $id"; exit 1; else echo "没画出 $id（看 log/$id.txt）"; fi
}
