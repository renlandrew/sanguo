#!/bin/bash
# 11-12 讨伐另外两只怪物：山君（巨虎）、蛟，各三档形态。Codex 命令行出图（Plus 额度），透明底 PNG，放 美术/讨伐/<名>/form<N>.png，已有的跳过。
# 用法：bash 三国志/工具/画图/draw_hunt2.sh
C="/Applications/ChatGPT.app/Contents/Resources/codex-cli/CodexCLI.app/Contents/MacOS/codex"
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../.." && pwd)"
REF="$ROOT/美术/讨伐/黄巾力士/form1.png"
COMMON="游戏里的巨型怪物立绘，三国志怪题材，手绘厚涂风格（画风、笔触、精细度照第一张附图）。正面朝向观众，只画这一只怪物，占满画面，居中。背景必须完全透明（PNG 透明通道），不要地面、不要影子、不要文字、不要边框、不要光晕底色。"
draw() { # 目录 id 提示词 [上一形态]
  local OUT="$ROOT/美术/讨伐/$1" id="$2" p="$3" ref2="$4"
  [ -f "$OUT/$id.png" ] && { echo "have $1 $id"; return; }
  printf "%s" "用内置 image_gen 工具画一张图（只画这一张，不要写代码处理图片）。画完把图片文件复制到 $OUT/$id.png 然后结束。第一张附图是画风参考${ref2:+，第二张附图是同一只怪物的上一个形态，体型、花纹、脸要认得出是同一只}。
$COMMON
$p" | (cd "$OUT" && "$C" exec --skip-git-repo-check -s workspace-write -i "$REF" ${ref2:+-i "$ref2"} - > "log/$id.txt" 2>&1)
  if [ -f "$OUT/$id.png" ]; then echo "ok $1 $id"; elif grep -q "429\|usage_limit" "$OUT/log/$id.txt"; then echo "额度用完，停在 $1 $id"; exit 1; else echo "没画出 $1 $id（看 log/$id.txt）"; fi
}
S="$ROOT/美术/讨伐/山君"; J="$ROOT/美术/讨伐/蛟"
draw 山君 form1 "方图（1:1）。角色：山君——深山里成了精的巨虎，比马还大两圈。正面蹲伏、前爪按地、肩背高耸，头正对观众，金黄底色配粗黑条纹，额头的黑纹像一个王字的形状但不要写成文字；眼睛琥珀色、半眯着，神情冷静。四只爪子都在画面内，尾巴在身后扬起。"
draw 山君 form2 "方图（1:1）。角色：山君的第二形态（被打怒了）。和上一形态同一只巨虎，同样正面蹲伏的姿势，但全身毛炸起，黑条纹里透出暗红的光，张嘴露出獠牙低吼，眼睛变成血红，前爪抬起一只、爪尖伸出。" "$S/form1.png"
draw 山君 form3 "方图（1:1）。角色：山君的第三形态（狂暴）。和前面同一只巨虎，体型更大，毛色变成黑底金纹，条纹像烧着的金色火焰，肩背和尾巴上腾起金红色的火；仰头咆哮，双眼白炽，两只前爪离地、人立欲扑。" "$S/form1.png"
draw 蛟 form1 "横图（3:2，宽大于高）。角色：蛟——大河里的无角龙。长长的身子盘成三道拱起的大弯，从画面左边一直横到右边，中间那一段最高，头从正中间高高昂起、正对观众；青黑色鳞片、灰白的腹甲，背上一排短鳍，两只短前爪按在身前；头像蛇又像鳄，没有角，嘴闭着，眼睛青绿、冷冷地盯着前方。身上挂着水珠和几缕水草。"
draw 蛟 form2 "横图（3:2，宽大于高）。角色：蛟的第二形态（被打怒了）。和上一形态同一条蛟，同样的盘身横贯、头在正中昂起的构图，但鳞片竖起、鳞缝里透出青蓝色的电光，张开大嘴露出两排尖牙，喉咙里有一团青白的水光，背鳍张开。" "$J/form1.png"
draw 蛟 form3 "横图（3:2，宽大于高）。角色：蛟的第三形态（狂暴）。和前面同一条蛟，同样盘身横贯、头在正中昂起的构图，身子更粗，鳞片变成黑底带青金色的边，全身缠着青白色的闪电和翻卷的水浪；头上鼓出两个将要长角的肉瘤，仰头怒吼，双眼白炽。" "$J/form1.png"
